name = "Python"

print(name)
print(len(name))
print(name.upper())
print(name.lower())
print(name.capitalize())

# Indexing
print(name[0])
print(name[-1])

# Slicing
print(name[0:3])
print(name[:3])
print(name[3:])

# Replace
text = "I like Java"
text = text.replace("Java", "Python")
print(text)

# f-string
age = 20
print(f"I am {age} years old.")
